#!/usr/bin/env bash
#
# scripts/promote-learnings/build-learnings-index.sh
#
# Regenerate spec/learnings/README.md from the files in spec/learnings/.
# The index drifts every time someone adds a learning and forgets to
# touch README.md; this script makes the README a derived artifact so
# the heartbeat / CI can re-build it deterministically.
#
# Each learning file contributes one table row:
#
#   | Date | Topic | File | Status | Summary |
#
# Where:
#   Date     — frontmatter `date:` if present, else the leading
#              YYYY-MM-DD from the filename, else "—"
#   Topic    — first H1 of the file (with "# " stripped), trimmed
#   File     — clickable relative link
#   Status   — frontmatter `status:` if present, else "—"
#   Summary  — first non-empty line after the H1 that isn't itself
#              another heading, frontmatter, blockquote, or bullet
#              marker, truncated to 140 chars
#
# Usage:
#   AI_RULES_REPO=/path scripts/promote-learnings/build-learnings-index.sh \
#     [--check]   # exit 1 if README would change (CI gate), do not write
#     [--quiet]   # suppress per-file progress
#
# Exit codes:
#   0 — README written (or --check: README already matches)
#   1 — --check found drift OR no learning files found
#   2 — bad env / missing dir

set -uo pipefail

err() { echo "[build-learnings-index] ERROR: $*" >&2; }

CHECK=0
QUIET=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --check) CHECK=1; shift ;;
    --quiet) QUIET=1; shift ;;
    -h|--help)
      sed -n '2,/^set -uo/p' "$0" | sed 's/^# \{0,1\}//;/^set -uo/d'
      exit 0 ;;
    *) err "unknown arg: $1"; exit 2 ;;
  esac
done

if [[ -z "${AI_RULES_REPO:-}" ]]; then
  err "AI_RULES_REPO is not set."
  exit 2
fi
LEARN_DIR="$AI_RULES_REPO/spec/learnings"
if [[ ! -d "$LEARN_DIR" ]]; then
  err "$LEARN_DIR does not exist."
  exit 2
fi
README="$LEARN_DIR/README.md"

_extract_frontmatter() {
  # _extract_frontmatter <file> <key>  → value (empty if absent)
  # Reads only the first --- ... --- block.
  local f="$1" key="$2"
  awk -v k="$key" '
    NR==1 && $0=="---" {in_fm=1; next}
    in_fm && $0=="---" {exit}
    in_fm && $1==k":"  {sub(/^[^:]*: */,""); print; exit}
  ' "$f"
}

_extract_title() {
  # First "# Header" line.
  local f="$1"
  awk '/^# / {sub(/^# */,""); print; exit}' "$f"
}

_extract_summary() {
  # First non-empty content line after the H1 that isn't a heading,
  # blockquote, bullet, or frontmatter delimiter.
  local f="$1"
  awk '
    /^---$/ {fm = !fm; next}
    fm {next}
    /^# / {seen_h1=1; next}
    seen_h1 && NF && !/^#/ && !/^>/ && !/^[-*] / && !/^\*\*/ && !/^\|/ {
      print; exit
    }
  ' "$f" | sed 's/[[:space:]]\+$//'
}

_extract_date() {
  # Frontmatter date:, else YYYY-MM-DD prefix of basename, else empty.
  local f="$1"
  local d
  d=$(_extract_frontmatter "$f" "date")
  if [[ -z "$d" ]]; then
    d=$(basename "$f" | grep -oE '^20[0-9]{2}-[0-9]{2}-[0-9]{2}')
  fi
  printf '%s\n' "$d"
}

_truncate() {
  # _truncate <text> <max>  →  text truncated to <max> chars (ellipsis if cut)
  local s="$1" max="$2"
  if (( ${#s} <= max )); then
    printf '%s\n' "$s"
  else
    printf '%s…\n' "${s:0:$((max-1))}"
  fi
}

_escape_pipe() {
  # Escape `|` for Markdown tables.
  printf '%s\n' "${1//|/\\|}"
}

# Gather rows: <sort-key>\t<date>\t<topic>\t<filename>\t<status>\t<summary>
# Newest first. Files without a date sort last (sort-key prefix '0').
rows=()
shopt -s nullglob
for f in "$LEARN_DIR"/*.md; do
  base=$(basename "$f")
  case "$base" in
    README.md|_template.md) continue ;;
  esac

  date_val=$(_extract_date "$f")
  topic=$(_extract_title "$f")
  status=$(_extract_frontmatter "$f" "status")
  summary=$(_extract_summary "$f")

  [[ -z "$topic" ]]   && topic="(no title)"
  [[ -z "$status" ]]  && status="—"
  [[ -z "$summary" ]] && summary="—"
  [[ -z "$date_val" ]] && sort_prefix="0_zzzz-zz-zz" || sort_prefix="1_${date_val}"

  topic=$(_escape_pipe "$topic")
  summary=$(_escape_pipe "$(_truncate "$summary" 140)")
  status=$(_escape_pipe "$status")
  display_date="${date_val:-—}"

  rows+=( "$(printf '%s\t%s\t%s\t%s\t%s\t%s' \
    "$sort_prefix" "$display_date" "$topic" "$base" "$status" "$summary")" )
  (( QUIET )) || echo "indexed: $base" >&2
done

if [[ ${#rows[@]} -eq 0 ]]; then
  err "no learning files found under $LEARN_DIR"
  exit 1
fi

# Sort descending by date (newest first), keep no-date entries at bottom.
sorted=$(printf '%s\n' "${rows[@]}" | LC_ALL=C sort -r)

# Build the new README content.
new_content=$(cat <<'HEADER'
# Learnings Index

Key findings and discoveries about this repository, accumulated by agents and developers during development.

> **Generated by `scripts/promote-learnings/build-learnings-index.sh`.**
> Do not edit by hand — your changes will be overwritten on the next run.
> Add a new learning by dropping a file under `spec/learnings/` (with
> `date:` and `status:` in the frontmatter) and re-running the script.

## Purpose

Learnings capture **what we discovered** about this codebase — gotchas, patterns, constraints, integration quirks, performance characteristics, and anything else that would save time for the next person (or agent) working here.

Unlike specs (which define WHAT the system should do) and ADRs (which capture WHY we chose an approach), learnings capture **what we found out** while building and maintaining the system.

## Learnings

| Date | Topic | File | Status | Summary |
|------|-------|------|--------|---------|
HEADER
)
new_content+=$'\n'
while IFS=$'\t' read -r _ date_val topic base status summary; do
  new_content+="| $date_val | $topic | [$base]($base) | $status | $summary |"$'\n'
done <<< "$sorted"

if (( CHECK )); then
  if [[ -f "$README" ]] && diff -q <(printf '%s' "$new_content") "$README" >/dev/null 2>&1; then
    (( QUIET )) || echo "README is up to date."
    exit 0
  fi
  err "README drift detected — re-run without --check to regenerate."
  exit 1
fi

printf '%s' "$new_content" > "$README"
(( QUIET )) || echo "wrote $README (${#rows[@]} rows)"
exit 0
