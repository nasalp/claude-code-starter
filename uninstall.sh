#!/usr/bin/env bash
#
# uninstall.sh — reverse setup.sh.
#
# Removes every symlink in ~/.claude (and ~/.claude/skills) that points into
# this repo, and restores the most recent ~/.claude/settings.json.backup-* made by setup.sh. If there
# is no backup and settings.json still references this repo's hooks, it is
# removed. Nothing else in ~/.claude is touched.
#
# Flags:
#   --dry-run    Report what would change without touching anything.
#   --help, -h   Show this help.

set -euo pipefail

usage() {
    sed -n '/^# uninstall.sh/,/^$/p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

DRY_RUN=false
while [[ $# -gt 0 ]]; do
    case "$1" in
        --dry-run) DRY_RUN=true; shift ;;
        --help|-h) usage; exit 0 ;;
        *) echo "[uninstall] ERROR: unknown flag: $1" >&2; usage >&2; exit 1 ;;
    esac
done

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CLAUDE_HOME="$HOME/.claude"
count=0

act() {
    if [[ "$DRY_RUN" == "true" ]]; then
        echo "  would $*"
    else
        echo "  $*"
    fi
    count=$((count + 1))
}

if [[ ! -d "$CLAUDE_HOME" ]]; then
    echo "[uninstall] $CLAUDE_HOME does not exist — nothing to do."
    exit 0
fi

echo "[uninstall] 1) Removing symlinks in $CLAUDE_HOME that point into $REPO_ROOT"
# Top-level links, plus per-skill links setup.sh makes inside a pre-existing skills/ directory.
for item in "$CLAUDE_HOME"/* "$CLAUDE_HOME"/.[!.]* "$CLAUDE_HOME"/skills/*; do
    [[ -L "$item" ]] || continue
    target=$(readlink "$item")
    case "$target" in
        "$REPO_ROOT"/*)
            act "remove $item -> $target"
            [[ "$DRY_RUN" == "true" ]] || rm "$item"
            ;;
    esac
done

echo "[uninstall] 2) Restoring settings.json"
settings="$CLAUDE_HOME/settings.json"
latest_backup=$(ls -1 "$settings".backup-* 2>/dev/null | sort | tail -1 || true)
if [[ -n "$latest_backup" ]]; then
    act "restore $latest_backup -> $settings"
    [[ "$DRY_RUN" == "true" ]] || mv "$latest_backup" "$settings"
elif [[ -f "$settings" ]] && grep -qF "$REPO_ROOT/.claude" "$settings"; then
    act "remove $settings (generated by setup.sh, no backup to restore)"
    [[ "$DRY_RUN" == "true" ]] || rm "$settings"
else
    echo "  ok    settings.json not managed by this repo — left alone"
fi

echo
if [[ $count -eq 0 ]]; then
    echo "[uninstall] Nothing to remove."
elif [[ "$DRY_RUN" == "true" ]]; then
    echo "[uninstall] Dry run — $count change(s) would be made."
else
    echo "[uninstall] Done — $count change(s)."
fi
